"""Write docs/results.md from the step 3-6 tables in reports/tables (no number is typed by hand)."""
from __future__ import annotations

import pandas as pd

from .config import DOCS, REPORT_TABLES

NAMES = {"demographics": "Demographics", "routine": "Routine data", "phq8": "PHQ-8 score",
         "routine_phq8": "Routine data + PHQ-8", "phq9": "PHQ-9 score (contains outcome item)",
         "routine_phq9": "Routine data + PHQ-9 (contains outcome item)"}


def _t(name: str) -> pd.DataFrame:
    return pd.read_csv(REPORT_TABLES / name)


def _ci(row, m: str, fmt: str = "{:.3f}") -> str:
    return f"{fmt.format(row[m])} ({fmt.format(row[m + '_ci_low'])}–{fmt.format(row[m + '_ci_high'])})"


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def build() -> str:
    m = _t("step5_test_metrics.csv")
    sel = m[m["selected"]]
    hyp = _t("step5_hypotheses.csv")
    neg = _t("step5_screen_negative.csv")
    negd = _t("step5_screen_negative_differences.csv")
    cap = _t("step5_screen_then_flag.csv")
    fair = _t("step5_fairness_routine.csv")
    strict = _t("step5_sensitivity_si_strict.csv")
    cv = _t("step4_cv_results.csv")
    shap_r = _t("step6_shap_importance_routine.csv")
    ors = _t("step6_odds_ratios.csv").fillna({"unit": ""})
    prev = _t("step3_weighted_prevalence.csv")
    rr = _t("step3_risk_ratios.csv")

    out = ["# Results (steps 3–6)", "",
           "Generated by `python scripts/write_results.py` from `reports/tables/`. Do not edit by hand.",
           "Test set: 2015–2018 (10,202 adults, 383 cases). 95% CIs: paired bootstrap, 2,000 resamples of test adults; "
           "prevalences: survey design (strata × PSU, Taylor linearisation).", ""]

    o = prev[prev.group == "Overall"].iloc[0]
    out += ["## Step 3 — Exploratory analysis", "",
            f"- Weighted prevalence 2005–2018: **{o.pct:.2f}%** (95% CI {o.ci_low:.2f}–{o.ci_high:.2f}).",
            "- Highest crude risk ratios: " + "; ".join(f"{r.factor} {r.rr:.2f} ({r.ci_low:.2f}–{r.ci_high:.2f})"
                                                       for r in rr.head(5).itertuples()) + ".",
            "- Tables: `step3_weighted_prevalence.csv`, `step3_risk_ratios.csv`, `step3_risk_ratios_screen_negative.csv`, "
            "`step3_feature_correlations.csv`.", ""]

    rows = []
    for r in sel.itertuples():
        c = cv[(cv.feature_set == r.feature_set) & (cv.algorithm == r.algorithm) & (cv.strategy == "none") & (cv.outcome == "si")].iloc[0]
        s = sel[sel.feature_set == r.feature_set].iloc[0]
        rows.append({"Feature set": NAMES[r.feature_set], "Model": r.algorithm.upper(),
                     "CV PR-AUC": f"{c.cv_pr_auc:.3f}", "Test PR-AUC (95% CI)": _ci(s, "pr_auc"),
                     "Test ROC-AUC (95% CI)": _ci(s, "roc_auc"), "Brier": f"{s.brier:.4f}",
                     "Calibration slope": f"{s.calibration_slope:.2f}",
                     "Top 5%: recall": f"{s.recall_top5:.1%}", "Top 5%: precision": f"{s.precision_top5:.1%}"})
    order = list(NAMES)
    tab = pd.DataFrame(rows).assign(_o=lambda d: d["Feature set"].map({NAMES[k]: i for i, k in enumerate(order)}))
    out += ["## Step 4–5 — Models on the test set", "",
            f"Prevalence baseline (PR-AUC of a random model): {sel.observed.iloc[0]:.4f}. "
            "Algorithm per feature set chosen by CV PR-AUC on 2005–2014 only.", "",
            _md(tab.sort_values("_o").drop(columns="_o")), ""]

    h = hyp.copy()
    h["estimate (95% CI)"] = [f"{e:.4f} ({lo:.4f} to {hi:.4f})" for e, lo, hi in zip(h.estimate, h.ci_low, h.ci_high)]
    h["supported"] = h["supported"].map({True: "yes", False: "no"})
    out += ["## Hypotheses", "", _md(h[["hypothesis", "comparison", "metric", "estimate (95% CI)", "criterion", "supported"]]), ""]

    n = neg.copy()
    n["PR-AUC (95% CI)"] = [_ci(r, "pr_auc") for _, r in n.iterrows()]
    n["ROC-AUC (95% CI)"] = [_ci(r, "roc_auc") for _, r in n.iterrows()]
    n["PR-AUC / prevalence"] = n["pr_auc_over_prevalence"].map("{:.1f}".format)
    n["prevalence"] = n["prevalence"].map("{:.2%}".format)
    out += ["## Main question — adults the depression screen misses", "",
            _md(n[["screen", "model", "n", "cases", "prevalence", "PR-AUC (95% CI)", "ROC-AUC (95% CI)", "PR-AUC / prevalence"]]), ""]
    for r in negd.itertuples():
        out.append(f"- {r.comparison}: PR-AUC difference {r.estimate:.4f} (95% CI {r.ci_low:.4f} to {r.ci_high:.4f}).")
    out.append("")
    for r in cap.itertuples():
        out.append(f"- **Screen ({r.screen}), then flag the top 5% of screen-negatives by `{r.model}`:** "
                   f"screen catches {r.cases_caught_by_screen} of {r.test_cases} cases; flagging {r.screen_negative_flagged_top5} "
                   f"screen-negative adults catches {r.missed_cases_caught_by_model} of the {r.cases_missed_by_screen} missed cases "
                   f"({r.share_of_missed_cases_caught:.1%}; precision {r.precision_of_extra_flags:.1%}). "
                   f"Total: {r.total_cases_caught} of {r.test_cases} cases ({r.share_of_all_cases_caught:.1%}) with {r.total_flagged} adults flagged.")
    out.append("")

    f = fair.copy()
    f["ROC-AUC (95% CI)"] = [_ci(r, "roc_auc") for _, r in f.iterrows()]
    f["PR-AUC / prevalence"] = f["pr_auc_over_prevalence"].map("{:.1f}".format)
    f["recall @ top 5%"] = [_ci(r, "recall_at_global_top5", "{:.1%}") for _, r in f.iterrows()]
    out += ["## Fairness — routine-data model", "",
            _md(f[["attribute", "group", "n", "cases", "ROC-AUC (95% CI)", "PR-AUC / prevalence", "recall @ top 5%"]]), ""]

    s = strict.copy()
    for c in ["prevalence", "pr_auc", "roc_auc", "brier", "recall_top5", "precision_top5"]:
        s[c] = s[c].map("{:.3f}".format)
    out += ["## Sensitivity — stricter outcome (item 9 ≥ more than half the days)", "",
            _md(s[["model", "cases", "prevalence", "pr_auc", "roc_auc", "brier", "recall_top5", "precision_top5"]]), ""]

    top = shap_r.head(10)
    sig = ors[(ors.p_value < 0.05) & ~ors.feature.str.startswith("missing:")]
    out += ["## Step 6 — Explainability", "",
            "- Top SHAP features (routine-data model, mean |SHAP|, log-odds): "
            + ", ".join(f"{r.feature} {r.mean_abs_shap:.3f}" for r in top.itertuples()) + ".",
            "- Adjusted odds ratios with p < 0.05 (unpenalised LR, training set): "
            + "; ".join(f"{r.feature} {r.unit} {r.odds_ratio:.2f} ({r.ci_low:.2f}–{r.ci_high:.2f})".replace("  ", " ")
                        for r in sig.itertuples()) + ".",
            "- Individual explanations: `step6_patient_explanations.csv`, figure `17_patient_explanations.png`.", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    path = DOCS / "results.md"
    path.write_text(build() + "\n")
    print(f"Wrote {path}")
    return 0
