def cohort_by_cycle(df: pd.DataFrame) -> pd.DataFrame:
    """Sample size, outcome and cases missed by the depression screen, per cycle and in total."""
    def summary(g: pd.DataFrame) -> dict:
        si = g["si"] == 1
        return {
            "adults": len(g),
            "si_cases": int(si.sum()),
            "si_pct": round(100 * si.mean(), 2),
            "si_strict_cases": int((g["si_strict"] == 1).sum()),
            "si_with_phq8_below_10_pct": round(100 * (g.loc[si, "phq8_score"] < SCREEN_CUTOFF).mean(), 1),
            "si_with_phq9_below_10_pct": round(100 * (g.loc[si, "phq9_score"] < SCREEN_CUTOFF).mean(), 1),
        }
    rows = [{"cycle": cycle, "split": split, **summary(g)}
            for (cycle, split), g in df.groupby(["cycle", "split"])]
    rows.append({"cycle": "total", "split": "", **summary(df)})
    return pd.DataFrame(rows)


def missingness_by_cycle(df: pd.DataFrame) -> pd.DataFrame:
    names = [v.name for v in VARIABLES]
    table = df[names].isna().groupby(df["cycle"]).mean().T
    table["all"] = df[names].isna().mean()
    return (100 * table).round(1).rename_axis("variable").rename_axis(None, axis=1)


# --------------------------------------------------------------------------- #
# Harmonisation rules
# --------------------------------------------------------------------------- #
def _cycle_span(letters: str) -> str:
    return f"{CYCLE_LABELS[letters[0]][:4]}-{CYCLE_LABELS[letters[-1]][-4:]}"


def _source_text(var: Var) -> str:
    if isinstance(var.source, str):
        return f"`{var.source}`"
    return ", ".join(f"`{name}` ({_cycle_span(letters)})" for letters, name in var.source.items())


def _ages_kept(var: Var) -> str:
    if var.min_age is None and var.max_age is None:
        return "all"
    if var.max_age is None:
        return f"{var.min_age}+"
    return f"{var.min_age or 18}-{var.max_age}"


def cross_cycle_rules(variables: Sequence[Var] = VARIABLES) -> pd.DataFrame:
    """Variables whose source, age coverage or values differ between cycles, with the rule applied."""
    rows = []
    for v in variables:
        recoded = v.transform not in (None, yes_no)
        if recoded and not v.note:
            raise ValueError(f"{v.name}: has a transform but no note describing the rule")
        if recoded or isinstance(v.source, dict) or v.min_age is not None or v.max_age is not None:
            rows.append({"variable": v.name, "source": _source_text(v),
                         "ages_kept": _ages_kept(v), "rule": v.note})
    return pd.DataFrame(rows, columns=["variable", "source", "ages_kept", "rule"])


def missing_code_groups(variables: Sequence[Var] = VARIABLES) -> Dict[str, List[str]]:
    """Refused / don't know codes -> the variables in which they are set to missing."""
    groups: Dict[str, List[str]] = {}
    for v in variables:
        codes = ", ".join(str(code) for code in v.missing) or "none"
        groups.setdefault(codes, []).append(v.name)
    return groups


GENERAL_RULES = [
    "**Stored zeros.** SAS transport stores 0 as about 5.4e-79; every value below 1e-30 in "
    "absolute size is set to 0 on import.",
    "**Merge.** Within a cycle, all modules are left-joined on `SEQN` to the demographics file, "
    "so every participant is kept. The prescription file has one row per drug: its person-level "
    "answers (`RXDUSE`, `RXDCOUNT`) are merged, and the drugs go to a separate long table.",
    "**Cohort.** Adults (18+) who answered all nine PHQ-9 items. A refused or don't-know item "
    "counts as not answered.",
    "**Refused / don't know.** The codes depend on the variable (table below), because 7 and 9 "
    "are real answers for some variables, such as hours of sleep.",
    "**Age coverage.** A variable is kept only for the ages asked in every cycle and set to "
    "missing outside them, so missingness does not reveal the survey year in the temporal "
    "validation (H4).",
    "**Not collected.** A variable that a cycle did not collect is missing for that whole cycle.",
    "**Yes / no questions** are recoded from NHANES 1 = yes, 2 = no to 1 = yes, 0 = no.",
]


def harmonisation_markdown() -> str:
    lines = [
        "# Appendix: harmonisation rules (step 1)",
        "",
        "Generated by `python scripts/build_dataset.py` from `src/hidden_risk/variables.py`. "
        "Do not edit by hand. The full variable list is in [`codebook.md`](codebook.md).",
        "",
        "## Rules applied to every cycle",
        "",
        *[f"{i}. {rule}" for i, rule in enumerate(GENERAL_RULES, start=1)],
        "",
        "## Refused / don't know codes set to missing",
        "",
        "| Codes | Variables |",
        "|---|---|",
        *[f"| {codes} | {', '.join(f'`{name}`' for name in names)} |"
          for codes, names in missing_code_groups().items()],
        "",
        "## Variables that differ between cycles",
        "",
        "| Variable | NHANES source | Ages kept | Rule |",
        "|---|---|---|---|",
        *[f"| `{r.variable}` | {r.source} | {r.ages_kept} | {r.rule} |"
          for r in cross_cycle_rules().itertuples()],
    ]
    return "\n".join(lines) + "\n"


