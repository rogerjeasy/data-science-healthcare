def codebook_markdown() -> str:
    lines = [
        "# Codebook: `nhanes_2005_2018.parquet`",
        "",
        "Generated by `python scripts/build_dataset.py` from `src/hidden_risk/variables.py`. "
        "Do not edit by hand.",
        "",
        "Refused / don't know answers are missing (`NA`). Yes/no questions are coded 1 = yes, 0 = no. "
        "The rules behind the notes are in [`harmonisation_rules.md`](harmonisation_rules.md).",
        "",
        "| Variable | Description | Values | NHANES source | Notes |",
        "|---|---|---|---|---|",
    ]
    for name, text in DERIVED.items():
        lines.append(f"| `{name}` | {text} | | derived | |")
    for v in VARIABLES:
        values = "; ".join(f"{k} = {label}" for k, label in v.values.items()) or v.kind
        source = f"{v.module}: {_source_text(v)}"
        lines.append(f"| `{v.name}` | {v.label} | {values} | {source} | {v.note} |")
    return "\n".join(lines) + "\n"
