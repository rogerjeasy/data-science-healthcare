"""Step 1: build the analysis-ready datasets from the raw NHANES files.

Outputs
-------
data/processed/nhanes_2005_2018.parquet                adults with a complete PHQ-9, one row each
data/processed/nhanes_2005_2018_prescriptions.parquet  their prescriptions, one row per drug
data/processed/nhanes_2021_2023_phq9.parquet           2021-23 PHQ-9 for the trend check
reports/tables/cohort_by_cycle.csv                     sample size and outcome per cycle
reports/tables/missingness_by_cycle.csv                % missing per variable and cycle
docs/codebook.md                                       every variable and its NHANES source
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from .cohort import PHQ_ITEMS, add_outcome, select_cohort
from .config import (CYCLE_LABELS, CYCLES, DATA_PROCESSED, DATA_RAW, DOCS, REPORT_TABLES,
                     TRAIN_CYCLES, TREND_CYCLE)
from .harmonise import harmonise_cycle, load_cycle, load_prescriptions
from .io import read_xpt
from .variables import BY_NAME, DERIVED, VARIABLES, Var

TREND_VARIABLES = ["age", "sex", "ethnicity", "weight_interview", "weight_mec", "strata", "psu",
                   *PHQ_ITEMS, "phq_difficulty"]


def build_persons(raw_dir: Path = DATA_RAW) -> pd.DataFrame:
    """Harmonised 2005-2018 cohort with outcome, split and pooled weight."""
    frames = []
    for cycle in CYCLES:
        print(f"  {CYCLES[cycle]}: merging and harmonising")
        frames.append(harmonise_cycle(load_cycle(cycle, raw_dir), cycle))
    df = add_outcome(select_cohort(pd.concat(frames, ignore_index=True)))
    train = df["cycle"].isin([CYCLES[c] for c in TRAIN_CYCLES])
    df.insert(2, "split", train.map({True: "train", False: "test"}))
    df["weight_mec_pooled"] = df["weight_mec"] / len(CYCLES)
    return df


def build_prescriptions(persons: pd.DataFrame, raw_dir: Path = DATA_RAW) -> pd.DataFrame:
    rx = pd.concat([load_prescriptions(c, raw_dir) for c in CYCLES], ignore_index=True)
    return rx[rx["seqn"].isin(persons["seqn"])].reset_index(drop=True)


def build_trend(raw_dir: Path = DATA_RAW) -> pd.DataFrame:
    raw = read_xpt(f"DEMO_{TREND_CYCLE}", raw_dir).merge(
        read_xpt(f"DPQ_{TREND_CYCLE}", raw_dir), on="SEQN", how="left", validate="one_to_one")
    variables = [BY_NAME[name] for name in TREND_VARIABLES]
    return add_outcome(select_cohort(harmonise_cycle(raw, TREND_CYCLE, variables)))


# --------------------------------------------------------------------------- #
# Reports
# --------------------------------------------------------------------------- #
def cohort_by_cycle(df: pd.DataFrame) -> pd.DataFrame:
    def summary(g: pd.DataFrame) -> dict:
        si = g["si"] == 1
        return {
            "adults": len(g),
            "si_cases": int(si.sum()),
            "si_pct": round(100 * si.mean(), 2),
            "si_strict_cases": int((g["si_strict"] == 1).sum()),
            "si_with_phq8_below_10_pct": round(100 * (g.loc[si, "phq8_score"] < 10).mean(), 1),
        }
    rows = [{"cycle": cycle, "split": split, **summary(g)}
            for (cycle, split), g in df.groupby(["cycle", "split"])]
    rows.append({"cycle": "total", "split": "", **summary(df)})
    return pd.DataFrame(rows)


def missingness_by_cycle(df: pd.DataFrame) -> pd.DataFrame:
    names = [v.name for v in VARIABLES]
    table = df[names].isna().groupby(df["cycle"]).mean().T
    table["all"] = df[names].isna().mean()
    return (100 * table).round(1).rename_axis("variable").rename_axis(None, axis=1)


def _cycle_span(letters: str) -> str:
    return f"{CYCLE_LABELS[letters[0]][:4]}-{CYCLE_LABELS[letters[-1]][-4:]}"


def _source_text(var: Var) -> str:
    if isinstance(var.source, str):
        return f"`{var.source}`"
    return ", ".join(f"`{name}` ({_cycle_span(letters)})" for letters, name in var.source.items())


def codebook_markdown() -> str:
    lines = [
        "# Codebook: `nhanes_2005_2018.parquet`",
        "",
        "Generated by `python scripts/build_dataset.py` from `src/hidden_risk/variables.py`. "
        "Do not edit by hand.",
        "",
        "Refused / don't know answers are missing (`NA`). Yes/no questions are coded 1 = yes, 0 = no.",
        "",
        "| Variable | Description | Values | NHANES source | Notes |",
        "|---|---|---|---|---|",
    ]
    for name, text in DERIVED.items():
        lines.append(f"| `{name}` | {text} | | derived | |")
    for v in VARIABLES:
        values = "; ".join(f"{k} = {label}" for k, label in v.values.items()) or v.kind
        source = f"{v.module}: {_source_text(v)}"
        lines.append(f"| `{v.name}` | {v.label} | {values} | {source} | {v.note} |")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--raw", type=Path, default=DATA_RAW, help="raw data folder (default: data/raw)")
    ap.add_argument("--out", type=Path, default=DATA_PROCESSED, help="output folder (default: data/processed)")
    args = ap.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    REPORT_TABLES.mkdir(parents=True, exist_ok=True)

    print("Building the 2005-2018 cohort")
    persons = build_persons(args.raw)
    prescriptions = build_prescriptions(persons, args.raw)
    trend = build_trend(args.raw)

    outputs = {
        "nhanes_2005_2018.parquet": persons,
        "nhanes_2005_2018_prescriptions.parquet": prescriptions,
        "nhanes_2021_2023_phq9.parquet": trend,
    }
    for name, df in outputs.items():
        df.to_parquet(args.out / name, index=False)
        print(f"Wrote {len(df):>7,} rows x {df.shape[1]:>2} columns -> {args.out / name}")

    cohort = cohort_by_cycle(persons)
    cohort.to_csv(REPORT_TABLES / "cohort_by_cycle.csv", index=False)
    missingness_by_cycle(persons).to_csv(REPORT_TABLES / "missingness_by_cycle.csv")
    (DOCS / "codebook.md").write_text(codebook_markdown())
    print(f"Wrote reports/tables/cohort_by_cycle.csv, reports/tables/missingness_by_cycle.csv, docs/codebook.md\n")
    print(cohort.to_string(index=False))
    return 0
